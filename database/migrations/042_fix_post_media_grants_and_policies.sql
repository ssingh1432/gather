-- Migration 042: fix post_media so photo/video/audio/document attachments
-- can actually be added to a post.
--
-- Root cause: public.post_media never had INSERT/DELETE granted to
-- `authenticated` (same class of bug as migration 041 — table reachable
-- by the client but missing the base grant, so Postgres rejects before
-- RLS is even consulted). `PostRepository.addPostMedia` (client) does a
-- delete-then-insert into this table for every image/video/audio/document
-- attached to a post, so every non-text post has been failing since
-- post_media was introduced. Plain text-only posts never touch
-- post_media, which is why they're the one post type that kept working.
--
-- Note: RLS policies for insert/delete on post_media (media_insert_post_owner,
-- media_delete_owner_or_admin) already existed live on the database but
-- were missing from this repo's migration history — they were correct and
-- are left as-is; this migration only adds the grant that was actually
-- missing.
grant select, insert, delete on public.post_media to authenticated;

